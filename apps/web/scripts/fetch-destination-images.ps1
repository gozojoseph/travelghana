# Downloads the curated destination hero photos (see scripts/destination-images/manifest.json)
# into public/destinations/<slug>.jpg and regenerates the ATTRIBUTIONS.txt credit list.
#
# The committed JPGs are the source of truth used by the web app; this script exists so
# the set can be reproduced deterministically from the recorded manifest. Images are
# fetched through commons.wikimedia.org/w/thumb.php (thumb.php?f=<file>&width=N), which
# keeps every request on one host and yields exactly one width per entry:
# min(1600, original width). Politeness: requests are throttled and -SkipExisting is
# the default, so re-runs only fetch what is missing.
param(
  [switch]$All # re-download everything instead of skipping files already on disk
)
$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$manifestPath = Join-Path $here "destination-images\manifest.json"
$outDir = Join-Path (Split-Path -Parent $here) "public\destinations"

$manifest = Get-Content -Path $manifestPath -Raw -Encoding utf8 | ConvertFrom-Json
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

$attribution = @(
  "TravelGhana destination hero photos - attribution",
  "Generated by apps/web/scripts/fetch-destination-images.ps1 from destination-images/manifest.json; do not edit by hand.",
  "Photos come from Wikimedia Commons. CC BY / CC BY-SA requires attribution - kept here and in docs.",
  ""
)

$fail = 0
foreach ($entry in $manifest.entries) {
  $dest = Join-Path $outDir ($entry.slug + ".jpg")
  if ((Test-Path $dest) -and -not $All) { continue }

  $fileName = $entry.file -replace "^File:", ""
  $width = [Math]::Min(1600, [int]$entry.width)
  $url = "https://commons.wikimedia.org/w/thumb.php?f=" + [uri]::EscapeDataString($fileName) + "&width=$width"

  try {
    Invoke-WebRequest -Uri $url -OutFile $dest -TimeoutSec 90 -UseBasicParsing -Headers @{ "User-Agent" = "TravelGhana-dev/0.1 (local development; photo attribution capture)" }
    $bytes = [System.IO.File]::ReadAllBytes($dest)
    if ($bytes.Length -lt 15000) { throw "too small ($($bytes.Length) bytes)" }
    if ($bytes[0] -ne 0xFF -or $bytes[1] -ne 0xD8) { throw "not a JPEG" }
    Write-Output ("OK   {0,-30} {1,7:N0} KB  w={2}" -f $entry.slug, ($bytes.Length / 1KB), $width)
  } catch {
    $fail++
    Write-Output ("FAIL {0,-30} {1}" -f $entry.slug, $_.Exception.Message)
  }
  Start-Sleep -Milliseconds 1200
}

# Attribution list covers every manifest entry whose file exists on disk (not just this run's downloads).
foreach ($entry in $manifest.entries) {
  if (Test-Path (Join-Path $outDir ($entry.slug + ".jpg"))) {
    $attribution += ("{0}.jpg - {1} - by {2} - {3} - {4}" -f $entry.slug, $entry.file, $entry.author, $entry.license, $entry.page)
  }
}
[System.IO.File]::WriteAllLines((Join-Path $outDir "ATTRIBUTIONS.txt"), $attribution, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ""
if ($fail -gt 0) { Write-Output "FAILED downloads: $fail"; exit 1 }
Write-Output "done; attributions written."
